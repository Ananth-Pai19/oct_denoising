"""
Assemble report/report.md from report/report_template.md plus the tables generated by the
experiment scripts.  Every number in the report therefore comes from a results/ file, not
from a hand-typed value.

    .venv/bin/python scripts/07_build_report.py
"""

from __future__ import annotations

import csv
import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
RES = os.path.join(ROOT, "results")
TEMPLATE = os.path.join(ROOT, "report", "report_template.md")
OUT = os.path.join(ROOT, "report", "report.md")

VARS = [0.02, 0.04, 0.06, 0.08, 0.10]
ORDER = ["Noisy", "HMF", "HWT", "DTCWT", "NCDF", "ACED", "VO", "TGV"]


def read_csv(path):
    with open(path, newline="") as fh:
        return list(csv.DictReader(fh))


def read_json(path):
    with open(path) as fh:
        return json.load(fh)


def table_synth():
    rows = read_csv(os.path.join(RES, "synthetic", "table2.csv"))
    lut = {(r["method"], float(r["var"])): r for r in rows}
    out = []
    for metric in ("PSNR", "SNR", "RMSE", "SSIM"):
        out.append(f"**{metric}**")
        out.append("")
        out.append("| Method | " + " | ".join(f"σ²={v:g}" for v in VARS) + " |")
        out.append("|---|" + "---|" * len(VARS))
        # RMSE is better when smaller, the other three when larger
        pick = min if metric == "RMSE" else max
        best = {v: pick((float(lut[(m, v)][metric]) for m in ORDER[1:])) for v in VARS}
        for m in ORDER:
            cells = []
            for v in VARS:
                val = float(lut[(m, v)][metric])
                star = " **" if abs(val - best[v]) < 1e-12 else " "
                cells.append(f"{val:.4f}{star}")
            out.append(f"| {m} | " + " | ".join(cells) + " |")
        out.append("")
    return "\n".join(out)


def table_vs_paper():
    rows = read_csv(os.path.join(RES, "synthetic", "table2.csv"))
    lut = {(r["method"], float(r["var"])): r for r in rows}
    import importlib.util
    spec = importlib.util.spec_from_file_location(
        "syn", os.path.join(ROOT, "scripts", "03_synthetic.py"))
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    paper = mod.PAPER
    out = ["| Method | metric | " + " | ".join(f"σ²={v:g}" for v in VARS) + " |",
           "|---|---|" + "---|" * len(VARS)]
    for m in ORDER:
        for metric in ("PSNR", "SSIM"):
            cells = []
            for i, v in enumerate(VARS):
                val = float(lut[(m, v)][metric])
                pv = paper[m][metric][i]
                d = val - pv
                cells.append(f"{val:.3f} ({d:+.3f})")
            out.append(f"| {m} | {metric} | " + " | ".join(cells) + " |")
    out.append("")
    out.append("Values are `ours (ours − paper)`.  The paper's transcribed Table 2 is in "
               "`results/synthetic/table2_paper.md`.")
    return "\n".join(out)


def table_staircase():
    st = read_json(os.path.join(RES, "verification", "staircase_stats.json"))
    out = ["| method | params | PSNR | SSIM | locally-flat fraction | slope recovered |",
           "|---|---|---|---|---|---|"]
    out.append(f"| TV (Vese–Osher) | α₁={st['tv_alpha1']:g}, β=0.1 | "
               f"{st['metrics_tv']['PSNR']:.2f} | {st['metrics_tv']['SSIM']:.4f} | "
               f"{st['flat_fraction_TV']*100:.1f}% | {st['slope_ratio_TV']*100:.0f}% |")
    p = st["tgv_params"]
    out.append(f"| TGV² | α₀={p['alpha0']:g}, α₁={p['alpha1']:g}, β={p['beta']:g} | "
               f"{st['metrics_tgv']['PSNR']:.2f} | {st['metrics_tgv']['SSIM']:.4f} | "
               f"{st['flat_fraction_TGV']*100:.1f}% | {st['slope_ratio_TGV']*100:.0f}% |")
    out.append(f"| noisy input | — | {st['metrics_noisy']['PSNR']:.2f} | "
               f"{st['metrics_noisy']['SSIM']:.4f} | — | — |")
    return "\n".join(out)


def table_runtime():
    tim = read_csv(os.path.join(RES, "synthetic", "timings.csv"))
    conv = read_json(os.path.join(RES, "verification", "convergence_stats.json"))
    out = ["| method | mean time per 256×256 frame (s) |", "|---|---|"]
    for r in tim:
        out.append(f"| {r['method']} | {float(r['mean_time_s']):.3f} |")
    out.append("")
    out.append(f"TGV² iterations to the paper's tolerance (`rel. change < 1e-3`): "
               f"**{conv['n_iter_tol1e-3']}** iterations, {conv['time_s_tol1e-3']:.2f} s, "
               f"PSNR {conv['metrics_tol1e-3']['PSNR']:.2f} dB, "
               f"SSIM {conv['metrics_tol1e-3']['SSIM']:.4f}.")
    out.append("")
    out.append(f"Run to `rel. change < 1e-6`: **{conv['n_iter_converged']}** iterations, "
               f"{conv['time_s']:.1f} s, PSNR {conv['metrics']['PSNR']:.2f} dB, "
               f"SSIM {conv['metrics']['SSIM']:.4f}.")
    return "\n".join(out)


def table_real():
    rows = read_csv(os.path.join(RES, "real", "table_real.csv"))
    import re
    for r in rows:                      # normalise "TGV_matched(x1.5)" etc.
        r["method"] = re.sub(r"\s*\(.*\)$", "", r["method"]).strip()
    cases = sorted({r["case"] for r in rows}, key=int)
    names = []
    for r in rows:
        if r["method"] not in names:
            names.append(r["method"])
    lut = {(r["case"], r["method"]): r for r in rows}
    out = ["| method | " + " | ".join(f"case {c}: σ_flat / ENL / SSIM$_{{avg}}$"
                                      for c in cases) + " |",
           "|---|" + "---|" * len(cases)]
    for m in names:
        cells = []
        for c in cases:
            r = lut[(c, m)]
            cells.append(f"{float(r['sigma_flat']):.4f} / {float(r['ENL']):.1f} / "
                         f"{float(r['ssim_vs_avg']):.3f}")
        out.append(f"| {m} | " + " | ".join(cells) + " |")
    out.append("")
    out.append("`σ_flat` = residual standard deviation inside the 10% flattest 16×16 "
               "blocks of the input (lower = more noise removed in homogeneous tissue); "
               "`ENL` = mean²/var over the same blocks (higher = smoother); "
               "`SSIM_avg` = SSIM against the multi-frame average (pseudo-reference).")
    out.append("")
    out.append("Plateau fraction (share of in-tissue neighbouring pixel pairs that are "
               "exactly equal, i.e. a staircase):")
    out.append("")
    out.append("| method | " + " | ".join(f"case {c}" for c in cases) + " |")
    out.append("|---|" + "---|" * len(cases))
    for m in names:
        cells = [f"{float(lut[(c, m)]['plateau'])*100:.1f}%" for c in cases]
        out.append(f"| {m} | " + " | ".join(cells) + " |")
    return "\n".join(out)


def table_sens():
    rows = read_csv(os.path.join(RES, "sensitivity", "sweeps.csv"))
    params = []
    for r in rows:
        if r["param"] not in params:
            params.append(r["param"])
    out = ["| swept parameter | σ² | best value | PSNR at best | PSNR range over sweep | "
           "SSIM at best |", "|---|---|---|---|---|---|"]
    for p in params:
        for v in ("0.02", "0.06", "0.1"):
            sel = [r for r in rows if r["param"] == p and r["var"] == v]
            if not sel:
                continue
            best = max(sel, key=lambda r: float(r["PSNR"]))
            lo = min(float(r["PSNR"]) for r in sel)
            hi = max(float(r["PSNR"]) for r in sel)
            out.append(f"| {p} | {float(v):g} | {float(best['value']):g} | "
                       f"{float(best['PSNR']):.2f} | {lo:.2f} – {hi:.2f} | "
                       f"{float(best['SSIM']):.4f} |")
    return "\n".join(out)


def table_tuning():
    p = read_json(os.path.join(RES, "tuning", "chosen_parameters.json"))
    inv = read_csv(os.path.join(RES, "tuning", "penalty_invariance.csv"))
    out = ["| parameter | value |", "|---|---|",
           f"| α₀ | {p['alpha0']:g} |", f"| α₁ | {p['alpha1']:g} |",
           f"| β | {p['beta']:g} |",
           f"| λ₁ = λ₂ = λ₃ | {p['lam1']:g} |",
           f"| tolerance | 1e-3 (relative change of u) |",
           f"| max iterations | 300 |", ""]
    out.append("Penalty invariance at full convergence (`rel. change < 1e-5`), which shows "
               "the split-Bregman penalties do not change the minimiser of (2.11):")
    out.append("")
    out.append("| λ₁,λ₂,λ₃ | iterations | PSNR | SSIM |")
    out.append("|---|---|---|---|")
    for r in inv:
        out.append(f"| {float(r['lam1']):g}, {float(r['lam2']):g}, {float(r['lam3']):g} | "
                   f"{r['iters']} | {float(r['psnr']):.4f} | {float(r['ssim']):.4f} |")
    return "\n".join(out)


def table_baseline():
    best = read_json(os.path.join(RES, "baselines", "best_params.json"))
    out = ["| method | tuned setting (σ²=0.04) |", "|---|---|"]
    for k, v in best.items():
        out.append(f"| {k} | `{json.dumps(v)}` |")
    return "\n".join(out)


def table_verify():
    txt = open(os.path.join(RES, "verification", "operator_tests.txt")).read().strip()
    return "```\n" + txt + "\n```"


FILLERS = {
    "TABLE_VERIFY": table_verify,
    "TABLE_TUNING": table_tuning,
    "TABLE_SYNTH": table_synth,
    "TABLE_VS_PAPER": table_vs_paper,
    "TABLE_STAIRCASE": table_staircase,
    "TABLE_RUNTIME": table_runtime,
    "TABLE_REAL": table_real,
    "TABLE_SENS": table_sens,
    "TABLE_BASELINE": table_baseline,
}


def main():
    text = open(TEMPLATE).read()
    for key, fn in FILLERS.items():
        text = text.replace("{{" + key + "}}", fn())
    assert "{{" not in text, "unfilled marker: " + text[text.index("{{"):text.index("{{") + 40]
    with open(OUT, "w") as fh:
        fh.write(text)
    print(f"wrote {OUT} ({len(text)} chars)")


if __name__ == "__main__":
    main()
